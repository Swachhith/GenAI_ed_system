"""Deliberate error injection, to prove the evaluator catches real problems.

Each mode plants one known defect into a lesson. `run --inject MODE` plants it into the
first draft; `calibrate` plants every mode into a known-good lesson and measures which
checks fire (see calibrate.py). `expected` must fail; `also` may fail without counting
as spillover.
"""
from __future__ import annotations

import re

INJECTIONS = {
    # A classic RAG misconception, phrased confidently.
    "factual": {
        "section": "how does",
        "text": ("Here is the secret: RAG works by retraining the AI model on your documents. "
                 "After that, the model remembers them forever, so its answers are always correct."),
        # "AI model" now appears before the lesson explains it, so L3 failing is correct too.
        "expected": ["L1_ACCURACY"], "also": ["L3_JARGON"],
    },
    # Subtle: no misconception keyword, just a quiet overclaim inside a true-sounding sentence.
    "overclaim": {
        "section": "why does",
        "text": "Because the AI reads your real documents, RAG stops it from making up answers.",
        "expected": ["L1_ACCURACY"], "also": [],
    },
    # Subtle: wrong about who searches.
    "wrong-actor": {
        "section": "how does",
        "text": "In RAG, the LLM goes onto the internet by itself and searches Google before it answers.",
        "expected": ["L1_ACCURACY"], "also": [],
    },
    # Dense, undefined jargon.
    "jargon": {
        "section": "how does",
        "text": ("Internally, the retriever computes cosine similarity between dense vector embeddings "
                 "stored in an HNSW index and returns the top-k chunks to the orchestration layer."),
        "expected": ["L3_JARGON"], "also": ["L5_LEARNER_FIT", "R3_READABILITY", "L6_FLOW"],
    },
    # Idioms a non-native reader would not understand.
    "idiom": {
        "section": "why does",
        "text": "Don't worry, this part is a piece of cake. Once you get the hang of it, you will be over the moon.",
        "expected": ["L5_LEARNER_FIT"], "also": [],
    },
    # One very long, complex sentence.
    "long-sentence": {
        "section": "what is rag",
        "text": ("Retrieval-Augmented Generation, which is a methodology that researchers and engineers "
                 "frequently utilise in contemporary artificial intelligence applications in order to "
                 "substantially enhance the factual reliability of responses generated by large language "
                 "models, fundamentally combines information retrieval with text generation."),
        "expected": ["R2_SENTENCES"], "also": ["R3_READABILITY", "L5_LEARNER_FIT"],
    },
    # A plausible but invented video link, the classic way models make up references.
    "fake-link": {
        "section": "learn more",
        "text": "- [RAG full course in 10 minutes](https://www.youtube.com/watch?v=Xr4G7aQ2pLm) - a quick video course.",
        "expected": ["R6_RESOURCES"], "also": [],
    },
    # A whole required section deleted. Coverage may still pass: the recap also says RAG can fail.
    "missing-limits": {
        "remove_section": "cannot",
        "expected": ["R1_STRUCTURE"], "also": ["L2_COVERAGE", "L6_FLOW", "R4_LENGTH"],
    },
}


def inject(lesson: str, mode: str) -> str:
    spec = INJECTIONS[mode]
    if "remove_section" in spec:
        return re.sub(rf"^##\s+[^\n]*{re.escape(spec['remove_section'])}[^\n]*\n.*?(?=^##\s)", "", lesson,
                      count=1, flags=re.I | re.M | re.S)
    # Insert as the first paragraph under the target H2 heading.
    pattern = re.compile(rf"^(##\s+[^\n]*{re.escape(spec['section'])}[^\n]*\n)", re.I | re.M)
    if pattern.search(lesson):
        return pattern.sub(lambda m: m.group(1) + "\n" + spec["text"] + "\n", lesson, count=1)
    return lesson.rstrip() + "\n\n" + spec["text"] + "\n"
